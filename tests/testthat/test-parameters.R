test_that("parameter updates change the solution and invalidate caches", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  p <- opt_parameter(m, "p", value = 1)
  opt_objective(m, (x - p)^2)
  r1 <- opt_solve(m)
  expect_equal(opt_value(r1, x), 1, tolerance = 1e-6)
  key1 <- opt_standard_form(m)$key
  opt_set_parameter(m, p, 5)
  expect_false(identical(opt_standard_form(m)$key, key1))
  r2 <- opt_solve(m)
  expect_equal(opt_value(r2, x), 5, tolerance = 1e-6)
  # stored results keep the parameter values they were solved with
  expect_equal(opt_value(r1, x - p), 0, tolerance = 1e-6)
  expect_equal(opt_value(r2, p), 5)
})

test_that("a parameter multiplying a quadratic term still gives a QP", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  p <- opt_parameter(m, "p", value = 2)
  opt_objective(m, p * x^2 - 4 * x)
  expect_identical(opt_classify(m)$class, "QP")
  expect_equal(opt_value(opt_solve(m), x), 1, tolerance = 1e-6)
  opt_set_parameter(m, p, -1)
  expect_identical(opt_classify(m)$convexity, "nonconvex")
  expect_error(opt_solve(m, solver = "highs"), "nonconvex")
})

test_that("parameters in constraint coefficients and right-hand sides", {
  m <- opt_model("max")
  x <- opt_variable(m, "x", dim = 2, lower = 0)
  a <- opt_parameter(m, "a", value = c(1, 2))
  b <- opt_parameter(m, "b", value = 4)
  opt_constraint(m, sum(a * x) <= b)
  opt_objective(m, sum(x))
  expect_identical(opt_classify(m)$class, "LP")
  expect_equal(opt_objective_value(opt_solve(m)), 4)
  opt_set_parameter(m, a, c(4, 1))
  opt_set_parameter(m, "b", 8)
  expect_equal(opt_objective_value(opt_solve(m)), 8)
  sf <- opt_standard_form(m)
  expect_equal(as.vector(sf$A), c(4, 1))
  expect_equal(sf$row_upper, 8)
})

test_that("parameter values are validated", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  p <- opt_parameter(m, "p", value = 1)
  expect_error(opt_set_parameter(m, x, 2), "parameters")
  expect_error(opt_set_parameter(m, p, NA), "missing")
  expect_error(opt_set_parameter(m, p, Inf), "finite")
  expect_error(opt_parameter(m, "q", value = c(1, 2), dim = 3), "length")
})
