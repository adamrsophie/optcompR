test_that("variables validate bounds and types", {
  m <- opt_model()
  expect_error(opt_variable(m, "a", lower = 2, upper = 1), "Contradictory")
  expect_error(opt_variable(m, "b", type = "integer", lower = 0.2, upper = 0.8),
               "no integer")
  expect_error(opt_variable(m, "c", type = "binary", lower = 2), "Binary")
  expect_error(opt_variable(m, "d", type = "real"))
  expect_error(opt_variable(m, "e", dim = 2, lower = c(0, 1, 2)), "length")
  x <- opt_variable(m, "x", type = "binary")
  v <- opt_variables(m)
  expect_equal(v$lower, 0)
  expect_equal(v$upper, 1)
  expect_error(opt_variable(m, "x"), "already")
})

test_that("bounds, types and fixing can be changed", {
  m <- opt_model()
  x <- opt_variable(m, "x", dim = 2)
  opt_set_bounds(m, x, lower = 0, upper = c(1, 5))
  expect_equal(opt_variables(m)$upper, c(1, 5))
  opt_fix(m, x[2], 3)
  expect_equal(opt_variables(m)$lower, c(0, 3))
  expect_error(opt_set_bounds(m, x[1], lower = 2), "Contradictory")
  opt_set_type(m, "x", "integer")
  expect_equal(opt_variables(m)$type, c("integer", "integer"))
  expect_error(opt_set_bounds(m, 2 * x, lower = 0), "plain")
})

test_that("model printing and listings", {
  m <- opt_model("max", name = "toy")
  x <- opt_variable(m, "x", dim = 2, lower = 0)
  opt_constraint(m, sum(x) <= 1, name = "budget")
  opt_objective(m, x[1])
  expect_output(print(m), "toy")
  expect_equal(opt_constraints(m)$name, "budget")
  expect_error(opt_constraint(m, x[1] <= 2, name = "budget"), "already")
  cn <- opt_constraint(m, x[2] <= 0.5)
  expect_output(print(cn), "c2")
  opt_delete_constraint(m, "budget")
  expect_equal(opt_constraints(m)$name, "c2")
})

test_that("constraint input is validated", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  expect_error(opt_constraint(m, TRUE), "TRUE/FALSE")
  expect_error(opt_constraint(m, x), "lower")
  expect_error(opt_constraint(m, x, lower = 2, upper = 1), "lower <= upper")
  expect_error(opt_objective(m, c(x, x)), "scalar")
})

test_that("models serialize together with their expressions", {
  m <- opt_model("max")
  x <- opt_variable(m, "x", lower = 0, upper = 2)
  opt_objective(m, 3 * x)
  f <- tempfile(fileext = ".rds")
  saveRDS(list(model = m, x = x), f)
  back <- readRDS(f)
  r <- opt_solve(back$model)
  expect_equal(opt_value(r, back$x), 2)
  expect_equal(opt_objective_value(r), 6)
})
