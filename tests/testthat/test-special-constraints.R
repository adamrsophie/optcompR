test_that("indicator constraints, native and reformulated", {
  m <- opt_model()
  x <- opt_variable(m, "x", lower = 0, upper = 8)
  on <- opt_variable(m, "on", type = "binary")
  opt_indicator(m, on, x <= 0, active = 0)
  opt_constraint(m, x >= 3)
  opt_objective(m, 2 * x + 10 * on)
  expect_identical(opt_classify(m)$class, "MILP")
  r <- opt_solve(m, solver = "highs")
  expect_equal(opt_value(r, c(x, on)), c(3, 1))
  expect_true(any(grepl("reformulated exactly", r$warnings)))
  expect_true(opt_check(r)$feasible)
  # with active = 1 and an upper bound on the relation
  m2 <- opt_model("max")
  y <- opt_variable(m2, "y", lower = 0, upper = 10)
  w <- opt_variable(m2, "w", type = "binary")
  opt_indicator(m2, w, y <= 4)
  opt_objective(m2, y + 5 * w)
  expect_equal(opt_objective_value(opt_solve(m2, solver = "highs")), 10)
  # unbounded variables cannot be reformulated
  m3 <- opt_model()
  u <- opt_variable(m3, "u", lower = 0)
  b <- opt_variable(m3, "b", type = "binary")
  opt_indicator(m3, b, u <= 1)
  opt_objective(m3, -b)
  expect_error(opt_solve(m3, solver = "highs"), "finite bounds")
  skip_if_not_installed("scip")
  expect_equal(opt_value(opt_solve(m, solver = "scip"), c(x, on)), c(3, 1))
  expect_equal(opt_objective_value(opt_solve(m2, solver = "scip")), 10)
  expect_equal(opt_objective_value(opt_solve(m3, solver = "scip")), -1)
})

test_that("SOS constraints and complementarity", {
  m <- opt_model()
  lam <- opt_variable(m, "lambda", dim = 4, lower = 0, upper = 1)
  u <- opt_variable(m, "u")
  opt_constraint(m, sum(lam) == 1)
  opt_constraint(m, u == sum(0:3 * lam))
  opt_constraint(m, u >= 1.5)
  opt_sos2(m, lam)
  opt_objective(m, sum((0:3)^2 * lam))
  expect_equal(opt_objective_value(opt_solve(m, solver = "highs")), 2.5)
  m1 <- opt_model("max")
  v <- opt_variable(m1, "v", dim = 3, lower = 0, upper = c(1, 2, 3))
  opt_sos1(m1, v)
  opt_objective(m1, sum(v))
  r1 <- opt_solve(m1, solver = "highs")
  expect_equal(opt_objective_value(r1), 3)
  expect_true(opt_check(r1)$feasible)
  # 0 <= a _|_ b >= 0 with a + b == 2 and an objective that wants both
  mc <- opt_model("max")
  a <- opt_variable(mc, "a", lower = 0, upper = 5)
  b <- opt_variable(mc, "b", lower = 0, upper = 5)
  opt_constraint(mc, a + 2 * b <= 4)
  opt_complementarity(mc, a, b)
  opt_objective(mc, a + 1.5 * b)
  rc <- opt_solve(mc)
  expect_equal(opt_value(rc, a) * opt_value(rc, b), 0)
  expect_equal(opt_objective_value(rc), 4)
  expect_error(opt_sos1(m1, v[1]), "at least two")
  skip_if_not_installed("scip")
  expect_equal(opt_objective_value(opt_solve(m, solver = "scip")), 2.5)
  expect_equal(opt_objective_value(opt_solve(m1, solver = "scip")), 3)
})

test_that("logical constraints are exact", {
  for (k in 0:3) {
    m <- opt_model("max")
    x <- opt_variable(m, "x", dim = 3, type = "binary")
    z <- opt_variable(m, "z", type = "binary")
    w <- opt_variable(m, "w", type = "binary")
    opt_and(m, z, x)
    opt_or(m, w, x)
    opt_constraint(m, sum(x) == k)
    opt_objective(m, z - w)
    r <- opt_solve(m)
    expect_equal(opt_value(r, z), as.numeric(k == 3))
    expect_equal(opt_value(r, w), as.numeric(k >= 1))
  }
  m <- opt_model()
  a <- opt_variable(m, "a", type = "binary")
  b <- opt_variable(m, "b", type = "binary")
  opt_implies(m, a, b)
  opt_constraint(m, a == 1)
  opt_objective(m, b)
  expect_equal(opt_value(opt_solve(m), b), 1)
  c1 <- opt_variable(m, "c1")
  expect_error(opt_implies(m, a, c1), "binary")
})

