test_that("second-order cones match the analytic distance and dual", {
  skip_if_not_installed("clarabel")
  m <- opt_model()
  x <- opt_variable(m, "x", dim = 2)
  t <- opt_variable(m, "t")
  line <- opt_constraint(m, sum(x) == 2, name = "line")
  opt_soc_constraint(m, x, t)
  opt_objective(m, t)
  expect_identical(opt_classify(m)$class, "SOCP")
  expect_identical(opt_classify(m)$convexity, "convex")
  r <- opt_solve(m)
  expect_identical(r$solver, "clarabel")
  expect_equal(opt_objective_value(r), sqrt(2), tolerance = 1e-7)
  # f*(b) = b / sqrt(2)
  expect_equal(unname(opt_dual(r, line)), 1 / sqrt(2), tolerance = 1e-6)
  d <- opt_check(r)
  expect_true(d$feasible)
  expect_null(d$kkt)
  skip_if_not_installed("scip")
  expect_equal(opt_objective_value(opt_solve(m, solver = "scip")), sqrt(2),
               tolerance = 1e-6)
})

test_that("cone duals are shadow prices in both senses", {
  skip_if_not_installed("clarabel")
  build <- function(b, sense) {
    m <- opt_model(sense)
    x <- opt_variable(m, "x", dim = 2)
    t <- opt_variable(m, "t")
    opt_constraint(m, x[1] + 2 * x[2] >= b, name = "cut")
    opt_constraint(m, t <= 10)
    opt_soc_constraint(m, x, t)
    opt_objective(m, if (sense == "min") t else -t)
    m
  }
  for (sense in c("min", "max")) {
    r <- opt_solve(build(3, sense))
    h <- 1e-4
    fd <- (opt_objective_value(opt_solve(build(3 + h, sense))) -
             opt_objective_value(opt_solve(build(3 - h, sense)))) / (2 * h)
    expect_equal(unname(opt_dual(r, "cut")), fd, tolerance = 1e-5)
  }
})

test_that("PSD, exponential and power cones", {
  skip_if_not_installed("clarabel")
  m <- opt_model("max")
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y")
  one <- 0 * x + 1
  zero <- 0 * x
  E <- c(one, x, zero, x, one, y, zero, y, one)
  dim(E) <- c(3, 3)
  opt_psd_constraint(m, E)
  opt_objective(m, x + y)
  expect_identical(opt_classify(m)$class, "CONIC")
  expect_equal(opt_objective_value(opt_solve(m)), sqrt(2), tolerance = 1e-6)

  A <- matrix(c(2, 1, 1, 3), 2)
  m <- opt_model()
  X <- opt_sym_variable(m, "X", 2)
  t <- opt_variable(m, "t")
  opt_constraint(m, X == t * diag(2) - A)
  opt_psd_constraint(m, X)
  opt_objective(m, t)
  expect_equal(opt_objective_value(opt_solve(m)), max(eigen(A)$values),
               tolerance = 1e-6)

  m <- opt_model()
  x <- opt_variable(m, "x", lower = 1)
  t <- opt_variable(m, "t")
  opt_exp_cone(m, x, 0 * x + 1, t)
  opt_objective(m, t)
  expect_equal(opt_objective_value(opt_solve(m)), exp(1), tolerance = 1e-6)

  m <- opt_model("max")
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y")
  z <- opt_variable(m, "z")
  opt_constraint(m, x + y <= 2)
  opt_pow_cone(m, x, y, z, 0.3)
  opt_objective(m, z)
  r <- opt_solve(m)
  expect_equal(opt_objective_value(r), 2 * 0.3^0.3 * 0.7^0.7, tolerance = 1e-6)
  expect_true(opt_check(r)$feasible)
  expect_error(opt_pow_cone(m, x, y, z, 1.5), "strictly between")
  expect_error(opt_soc_constraint(m, x^2, z), "affine")
})

