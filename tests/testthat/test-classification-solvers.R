test_that("classes are recognized", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y", type = "integer")
  opt_objective(m, x + y)
  expect_identical(opt_classify(m)$class, "MILP")
  opt_objective(m, x^2 + y)
  expect_identical(opt_classify(m)$class, "MIQP")
  opt_set_type(m, y, "continuous")
  expect_identical(opt_classify(m)$class, "QP")
  opt_constraint(m, x^2 + y^2 <= 1)
  expect_identical(opt_classify(m)$class, "QCQP")
  opt_constraint(m, exp(x) <= 3)
  expect_identical(opt_classify(m)$class, "NLP")
  expect_identical(opt_classify(m)$convexity, "unknown")
})

test_that("convexity uses Hessian analysis, not syntax", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y")
  opt_objective(m, x^2 + x * y + y^2)
  cl <- opt_classify(m)
  expect_identical(cl$convexity, "convex")
  expect_match(cl$evidence[2], "numerical eigenvalues")
  opt_objective(m, x^2 - 3 * x * y + y^2)
  expect_identical(opt_classify(m)$convexity, "nonconvex")
  opt_objective(m, x^2 + y^2, sense = "max")
  expect_identical(opt_classify(m)$convexity, "nonconvex")
  opt_objective(m, -x^2 - y^2, sense = "max")
  expect_identical(opt_classify(m)$convexity, "convex")
  # diagonal forms are decided structurally
  opt_objective(m, 2 * x^2 + y^2, sense = "min")
  expect_match(opt_classify(m)$evidence[2], "structural")
})

test_that("quadratic constraints are checked for convex feasible sets", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y")
  opt_objective(m, x + y)
  opt_constraint(m, x^2 + y^2 <= 1)
  expect_identical(opt_classify(m)$convexity, "convex")
  opt_constraint(m, x^2 + y^2 >= 0.5)
  expect_identical(opt_classify(m)$convexity, "nonconvex")
})

test_that("singular and nearly singular quadratic forms", {
  m <- opt_model()
  x <- opt_variable(m, "x")
  y <- opt_variable(m, "y")
  opt_objective(m, (x + y)^2 + x)
  cl <- opt_classify(m)
  expect_identical(cl$convexity, "convex")
  expect_match(cl$evidence[2], "tolerance boundary")
  opt_constraint(m, x >= -1)
  opt_constraint(m, y <= 3)
  r <- opt_solve(m)
  expect_true(opt_status(r) %in% c("optimal", "unbounded",
                                   "infeasible_or_unbounded"))
})

test_that("solver registry reports capabilities", {
  s <- opt_solvers()
  expect_true("highs" %in% s$solver)
  cap <- opt_solver_capabilities("highs")
  expect_true(cap$available)
  expect_true(all(c("LP", "MILP", "QP") %in% cap$classes))
  expect_true(cap$features$duals)
  expect_error(opt_solver_capabilities("nonexistent"), "Unknown solver")
})

test_that("unsupported classes give clear errors instead of approximations", {
  m <- opt_model()
  x <- opt_variable(m, "x", lower = 0, upper = 1)
  y <- opt_variable(m, "y", type = "integer", lower = 0, upper = 3)
  opt_objective(m, x^2 + y^2 - 3 * x * y)
  expect_error(opt_solve(m, solver = "highs"), "does not support MIQP")
  opt_set_type(m, y, "continuous")
  expect_error(opt_solve(m, solver = "highs"), "nonconvex")
})

test_that("solver options and results metadata", {
  m <- opt_model()
  x <- opt_variable(m, "x", lower = 1)
  opt_objective(m, x)
  r <- opt_solve(m, solver = "highs", options = list(presolve = "off"))
  expect_identical(r$solver, "highs")
  expect_true(nzchar(r$solver_version))
  expect_true(all(c("time", "R", "optcompR") %in% names(r$metadata)))
  expect_output(print(r), "optimal")
  expect_output(print(summary(r)), "Variables")
  expect_error(opt_solve(m, time_limit = -1), "positive")
})
